-- CareLake Snowflake bootstrap.  STATUS: WRITTEN, NEVER EXECUTED (no account yet).
-- Run once, manually, as ACCOUNTADMIN. Review every line first: this creates billable objects.
-- Replace <CREDIT_QUOTA> with a small number you are comfortable spending (e.g. 5).
-- ============================================================================
USE ROLE ACCOUNTADMIN;

-- Roles: least privilege. LOADER writes RAW only; TRANSFORMER (dbt) reads RAW, writes ANALYTICS.
CREATE ROLE IF NOT EXISTS CARELAKE_LOADER;
CREATE ROLE IF NOT EXISTS CARELAKE_TRANSFORMER;

-- Cost guard: a resource monitor suspends the warehouse when the quota is hit.
CREATE RESOURCE MONITOR IF NOT EXISTS CARELAKE_RM
  WITH CREDIT_QUOTA = <CREDIT_QUOTA> FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;

-- XSMALL, suspends after 60 s idle, starts suspended: the cheapest sensible configuration.
CREATE WAREHOUSE IF NOT EXISTS CARELAKE_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  RESOURCE_MONITOR = CARELAKE_RM;

CREATE DATABASE IF NOT EXISTS CARELAKE;
CREATE SCHEMA IF NOT EXISTS CARELAKE.RAW;        -- append-only landing tables (COPY INTO)
CREATE SCHEMA IF NOT EXISTS CARELAKE.ANALYTICS;  -- dbt output (staging views, dims, facts, marts)
CREATE SCHEMA IF NOT EXISTS CARELAKE.DQ;         -- data-quality results

GRANT USAGE, OPERATE ON WAREHOUSE CARELAKE_WH TO ROLE CARELAKE_LOADER;
GRANT USAGE ON WAREHOUSE CARELAKE_WH TO ROLE CARELAKE_TRANSFORMER;
GRANT USAGE ON DATABASE CARELAKE TO ROLE CARELAKE_LOADER;
GRANT USAGE ON DATABASE CARELAKE TO ROLE CARELAKE_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA CARELAKE.RAW TO ROLE CARELAKE_LOADER;
GRANT USAGE ON SCHEMA CARELAKE.RAW TO ROLE CARELAKE_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA CARELAKE.RAW TO ROLE CARELAKE_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA CARELAKE.RAW TO ROLE CARELAKE_TRANSFORMER;
GRANT ALL ON SCHEMA CARELAKE.ANALYTICS TO ROLE CARELAKE_TRANSFORMER;
GRANT ALL ON SCHEMA CARELAKE.DQ TO ROLE CARELAKE_TRANSFORMER;

